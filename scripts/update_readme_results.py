r"""Write the results block of README.md from reports/metrics (Abin Shaji Thomas).

Replaces everything between <!-- RESULTS:START --> and <!-- RESULTS:END --> in README.md.
Run:  .venv\Scripts\python.exe scripts\update_readme_results.py
"""
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
M = ROOT / "reports" / "metrics"
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def j(name):
    return json.loads((M / name).read_text(encoding="utf-8"))


def md_table(df: pd.DataFrame) -> str:
    lines = ["| " + " | ".join(map(str, df.columns)) + " |", "|" + "|".join("---" for _ in df.columns) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join("-" if (isinstance(v, float) and v != v) else str(v) for v in r.values) + " |")
    return "\n".join(lines)


def model_table(comp: pd.DataFrame, distance: str) -> pd.DataFrame:
    t = comp[comp["distance_feature"] == distance]
    out = pd.DataFrame({"Model": t["model"]})
    for col, lab in [("accuracy", "Accuracy"), ("macro_f1", "Macro-F1"), ("weighted_f1", "Weighted-F1"),
                     ("roc_auc_ovr_macro", "ROC-AUC (OvR)"), ("recall_sev3", "Recall Sev 3"), ("recall_sev4", "Recall Sev 4")]:
        out[lab] = t[col].map(lambda v: "-" if v != v else f"{v:.3f}")
    return out


def block() -> str:
    prof, stats, log, gps = j("dataset_profile.json"), j("dataset_stats.json"), j("cleaning_log.json"), j("gps_missing.json")
    best, cross, mongo, cnt = j("best_model.json"), j("bigdata_crosscheck.json"), j("mongo_results.json"), j("mapreduce_counters.json")
    ins = j("eda_insights.json")
    comp = pd.read_csv(M / "model_comparison.csv")
    hot = pd.read_csv(M / "hotspots.csv")
    fi = pd.read_csv(M / "feature_importance.csv").head(5)
    d = log["duplicates"]
    q = pd.DataFrame(mongo["queries"])
    q = q[q["ms_without_index"].notna()]
    q["speed-up"] = (q["ms_without_index"] / q["ms_with_index"]).round(1)
    out = [
        "*Generated by `scripts/update_readme_results.py` from `reports/metrics/` - do not edit by hand.*", "",
        "**Data** (`dataset_profile.json`, `dataset_stats.json`, `cleaning_log.json`, `gps_missing.json`)", "",
        md_table(pd.DataFrame([
            ("Rows x columns (raw file)", f"{prof['rows']:,} x {prof['columns']}"),
            ("Period", f"{prof['start_time_min'][:10]} to {prof['start_time_max'][:10]}"),
            ("States", prof["n_states"]),
            ("Stratified sample / after cleaning", f"{stats['sample_rows']:,} / {log['rows_clean']:,}"),
            ("Duplicates removed", f"{d['duplicate_ids'] + d['duplicate_content']:,}"),
            ("Start GPS missing / recovered / dropped", f"{gps['before']['Start']['missing']:,} / {gps['start_recovered_city_state_median']:,} / {gps['start_dropped_unrecoverable']:,}"),
            ("End GPS imputed from Start", f"{gps['end_imputed_from_start']:,} ({100 * gps['end_imputed_from_start'] / gps['rows_after']:.1f}%)"),
        ], columns=["Item", "Value"])), "",
        "**EDA highlights** (`eda_insights.json`, `weather_tests.json`, `hotspots.csv`)", "",
        f"* Weather: {ins['weather']}",
        f"* Infrastructure: {ins['infrastructure']}",
        f"* Time: {ins['time']}",
        f"* Year: {ins['year_artifact']}",
        f"* Hotspots: densest 0.1-degree cells - " + ", ".join(f"{r.label} ({r.accidents:,})" for r in hot.drop_duplicates("label").head(4).itertuples()) + ".",
        "",
        "**Severity models - test set, WITHOUT Distance(mi) (headline)** (`model_comparison.csv`)", "",
        md_table(model_table(comp, "without")), "",
        f"Best model: **{best['best_model']}** (highest macro-F1), 5-fold CV macro-F1 {best['cv_5fold']['macro_f1_mean']:.3f} "
        f"+/- {best['cv_5fold']['macro_f1_std']:.3f}. Every model's accuracy is "
        f"{'below' if (comp[(comp.distance_feature == 'without') & (comp.model != 'Majority baseline')]['accuracy'] < best['baseline_majority']['accuracy']).all() else 'not always below'} "
        f"the majority baseline ({best['baseline_majority']['accuracy']:.3f}), so macro-F1 is the headline metric.",
        f"Top permutation-importance features: " + ", ".join(f"{r.feature} ({r.importance_mean:.4f})" for r in fi.itertuples()) + ".", "",
        "<details><summary>With Distance(mi) (post-event, leakage - reported for honesty only)</summary>", "",
        md_table(model_table(comp, "with")), "", "</details>", "",
        "**Big data** (`mongo_results.json`, `mapreduce_counters.json`, `bigdata_crosscheck.json`)", "",
        f"* MongoDB: {mongo['documents']:,} documents, {len(mongo['indexes'])} indexes, {mongo['n_queries']} queries timed; "
        f"indexed filters run {q['speed-up'].max():.0f}x faster at best ({q.loc[q['speed-up'].idxmax(), 'name']}).",
        f"* MapReduce: {cnt['jobs']['state']['splits']} splits, {cnt['jobs']['state']['map_tasks']} map tasks, "
        f"{cnt['jobs']['state']['reduce_tasks']} reduce tasks, {cnt['jobs']['state']['map_input_records']:,} records per job.",
        "* Cross-check MapReduce vs pandas vs MongoDB: " + ", ".join(f"{v['title']} **{v['status']}**" for v in cross["jobs"].values())
        + f" ({cross['values_compared']} values).",
    ]
    return "\n".join(out)


def main():
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    if START not in text or END not in text:
        sys.exit("README.md has no RESULTS markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    readme.write_text(head + START + "\n" + block() + "\n" + END + tail, encoding="utf-8")
    print("README results block updated")


if __name__ == "__main__":
    main()
